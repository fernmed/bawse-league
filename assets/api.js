/* Bawse League — shared data helpers for the section pages.
   The draft-room server on Render is the data backbone; its /api/public/*
   endpoints are unauthenticated, read-only, and CORS-allow this site
   (plus localhost for dev previews). */

const API_BASE = "https://draft.bawseleague.com";

/* Championship + league metadata shared across pages. */
const CHAMP = {MLB:"World Series", NBA:"NBA Finals", NHL:"Stanley Cup", NFL:"Super Bowl",
               NCAAF:"CFP National Title", NCAAM:"NCAA Tournament", EPL:"Premier League"};
const LEAGUE_ORDER = ["NFL", "MLB", "NBA", "NHL", "NCAAF", "NCAAM", "EPL"];

/* Fetch a public API payload. `bust` skips the browser's HTTP cache (the
   server sends max-age=300) — used while the draft is live so the board
   never sits five minutes stale. */
async function apiGet(path, {bust = false} = {}) {
  const url = API_BASE + path + (bust ? (path.includes("?") ? "&" : "?") + "t=" + Date.now() : "");
  const res = await fetch(url);
  if (!res.ok) throw new Error("API " + res.status + " for " + path);
  return res.json();
}

/* Team logo map (generated by dev/build_logos.py; misses fall back to
   league-colored monogram badges). Loaded once, never blocks first render. */
let LOGOS = {};
async function loadLogos() {
  try {
    const res = await fetch("/assets/logos.json");
    if (res.ok) LOGOS = await res.json();
  } catch (e) { /* monograms cover everything */ }
}

const LEAGUE_CSS = {MLB:"--c-mlb", NBA:"--c-nba", NHL:"--c-nhl", NFL:"--c-nfl",
                    NCAAF:"--c-ncaaf", NCAAM:"--c-ncaam", EPL:"--c-epl"};

function escapeHTML(s) {
  return String(s).replace(/[&<>"']/g, c => ({"&":"&amp;","<":"&lt;",">":"&gt;",'"':"&quot;","'":"&#39;"}[c]));
}

function initials(name) {
  const words = name.replace(/[()]/g, "").split(/[\s-]+/).filter(Boolean);
  if (words.length === 1) return words[0].slice(0, 3).toUpperCase();
  return words.slice(0, 3).map(w => w[0]).join("").toUpperCase();
}

function monogramHTML(name, league) {
  return `<div class="mono" style="background:var(${LEAGUE_CSS[league] || "--gold"})">${escapeHTML(initials(name))}</div>`;
}

/* Logo <img> with a monogram fallback baked into onerror, matching the
   pattern from the launch page. */
function logoHTML(teamId, name, league) {
  const url = LOGOS[teamId];
  if (!url) return monogramHTML(name, league);
  const mono = monogramHTML(name, league).replace(/"/g, "&quot;");
  return `<img src="${escapeHTML(url)}" alt="" loading="lazy" onerror="this.outerHTML='${mono}'">`;
}

/* American odds -> implied probability (0..1); null odds -> 0. */
function impliedProb(odds) {
  if (typeof odds !== "number" || odds === 0) return 0;
  return odds > 0 ? 100 / (odds + 100) : -odds / (-odds + 100);
}

function fmtOdds(odds) {
  if (typeof odds !== "number") return "—";
  return (odds > 0 ? "+" : "") + odds.toLocaleString();
}

function fmtMoney(n) {
  return "$" + n.toLocaleString(undefined, {maximumFractionDigits: 0});
}

function timeAgo(epoch) {
  const s = Math.max(0, Math.floor(Date.now() / 1000 - epoch));
  if (s < 60) return "just now";
  if (s < 3600) return Math.floor(s / 60) + "m ago";
  if (s < 86400) return Math.floor(s / 3600) + "h ago";
  return new Date(epoch * 1000).toLocaleDateString(undefined, {month: "short", day: "numeric"});
}
